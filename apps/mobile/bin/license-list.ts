// @ts-expect-error
import { scanDependencies } from "@callstack/licenses";
import fs from "node:fs";

type License = {
  id: string;
  name: string;
  content: string;
};

const licenses = scanDependencies("package.json");

const source: string[] = ["// @ts-nocheck", "// Auto-generated by license-list.ts", "export const licenses = {"];

for (const license of Object.keys(licenses)) {
  const content = licenses[license];
  source.push(
    `  "${license}": { id: "${license}", name: "${content.name}", content: \`${content.content?.replaceAll("`", "\\`")}\` },`,
  );
}

// assets/emoji/ にバンドルしている Twemoji の画像 (CC-BY 4.0) は依存パッケージではないため、個別に差し込む
const TWEMOJI_LICENSE = "./assets/emoji/LICENSE-GRAPHICS";
if (fs.existsSync(TWEMOJI_LICENSE)) {
  const content = [
    "Twemoji (https://github.com/jdecked/twemoji)",
    "Copyright 2019 Twitter, Inc and other contributors",
    "Copyright (c) 2022–present Jason Sofonia & Justine De Caires",
    "Graphics licensed under CC-BY 4.0: https://creativecommons.org/licenses/by/4.0/",
    "",
    fs.readFileSync(TWEMOJI_LICENSE, "utf-8"),
  ].join("\n");
  source.push(`  "twemoji": { id: "twemoji", name: "Twemoji", content: \`${content.replaceAll("`", "\\`")}\` },`);
}

source.push("};");

fs.writeFileSync("./src/lib/generated/licenses.ts", source.join("\n"));
