// Twemoji (https://github.com/jdecked/twemoji) の 72x72 PNG をアプリにバンドルするためのスクリプト
//
//   pnpm bin:emoji-gen    assets/emoji/ から src/lib/generated/emojis.ts を生成する (prebuilt で実行される)
//   pnpm emoji:fetch      TWEMOJI_VERSION の画像を取得して assets/emoji/ を置き換え、続けて emojis.ts を生成する
//
// Twemoji のファイル名 (1f1e9-1f1ec.png) は Android のリソース名として不正 (ハイフン・数字始まり) なので、
// e_1f1e9_1f1ec.png のように先頭に英字を付け、ハイフンをアンダースコアに置き換えて配置する。
// emojis.ts のキーは元の Twemoji 形式 (1f1e9-1f1ec) のまま。
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const TWEMOJI_VERSION = "17.0.3";

const ASSET_DIR = "./assets/emoji";
const OUTPUT = "./src/lib/generated/emojis.ts";

const TWEMOJI_KEY = /^[0-9a-f]+(?:-[0-9a-f]+)*$/;
const RESOURCE_NAME = /^e_([0-9a-f]+(?:_[0-9a-f]+)*)\.png$/;

const toResourceName = (key: string) => `e_${key.replaceAll("-", "_")}.png`;

async function fetchTwemoji() {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "twemoji-"));

  try {
    const url = `https://github.com/jdecked/twemoji/archive/refs/tags/v${TWEMOJI_VERSION}.tar.gz`;
    const response = await fetch(url);
    if (!response.ok) {
      throw new Error(`failed to download ${url}: ${response.status}`);
    }

    const archive = path.join(tmp, "twemoji.tar.gz");
    fs.writeFileSync(archive, Buffer.from(await response.arrayBuffer()));
    execFileSync("tar", ["-xzf", archive, "-C", tmp]);

    const root = path.join(tmp, `twemoji-${TWEMOJI_VERSION}`);
    const source = path.join(root, "assets", "72x72");

    fs.rmSync(ASSET_DIR, { recursive: true, force: true });
    fs.mkdirSync(ASSET_DIR, { recursive: true });

    for (const file of fs.readdirSync(source)) {
      const key = path.basename(file, ".png");
      if (!file.endsWith(".png") || !TWEMOJI_KEY.test(key)) {
        throw new Error(`unexpected file in twemoji assets: ${file}`);
      }
      fs.copyFileSync(path.join(source, file), path.join(ASSET_DIR, toResourceName(key)));
    }

    // 画像は CC-BY 4.0 のため、ライセンスも一緒に配置する
    fs.copyFileSync(path.join(root, "LICENSE-GRAPHICS"), path.join(ASSET_DIR, "LICENSE-GRAPHICS"));
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

function generate() {
  const source: string[] = [
    "// @ts-nocheck",
    "// Auto-generated by emoji-gen.ts",
    `// Twemoji ${TWEMOJI_VERSION} (https://github.com/jdecked/twemoji)`,
    "export const emojis = {",
  ];

  const files = fs.existsSync(ASSET_DIR) ? fs.readdirSync(ASSET_DIR).sort() : [];
  for (const file of files) {
    const match = RESOURCE_NAME.exec(file);
    if (!match) continue;

    const key = match[1].replaceAll("_", "-");
    source.push(`  "${key}": require("../../../assets/emoji/${file}"),`);
  }

  source.push("} as const;", "", "export type EmojiKey = keyof typeof emojis;", "");

  fs.writeFileSync(OUTPUT, source.join("\n"));
}

async function main() {
  if (process.argv.includes("--fetch")) {
    await fetchTwemoji();
  }

  generate();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
